// The baked standalone form of the ShipBench mark. The path/clip markup is
// lifted directly from docs/brand/logo-mark.svg; only the square tile ground
// and outer SVG document are supplied here.

const CANVAS = '#18171C';
const TILE_SIZE = 1500;

export function buildStandaloneLogoSvg(mark: string): string {
  const artworkStart = mark.indexOf('<defs>');
  const artworkEnd = mark.lastIndexOf('</svg>');
  if (artworkStart === -1 || artworkEnd === -1 || artworkStart >= artworkEnd) {
    throw new Error('The brand mark does not contain an SVG artwork body');
  }

  const artwork = mark.slice(artworkStart, artworkEnd).trim();
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${TILE_SIZE} ${TILE_SIZE}" width="${TILE_SIZE}" height="${TILE_SIZE}" role="img" aria-label="ShipBench">
  <title>ShipBench</title>
  <!-- Generated by pnpm generate:icons from docs/brand/logo-mark.svg. -->
  <rect width="${TILE_SIZE}" height="${TILE_SIZE}" fill="${CANVAS}" />

  ${artwork}
</svg>
`;
}

export function buildIconHtml(svgDataUri: string, size: number): string {
  return `<!doctype html>
<html>
<head>
<meta charset="utf-8">
<style>
  * { margin: 0; padding: 0; }
  html, body, img { width: ${size}px; height: ${size}px; }
  img { display: block; }
</style>
</head>
<body><img src="${svgDataUri}" alt=""></body>
</html>`;
}
